const MAX_ERROR_LOG_CHARS = 16000;

function capLogText(text: string): string {
	if (text.length <= MAX_ERROR_LOG_CHARS) return text;
	return '...[truncated]...\n' + text.slice(-MAX_ERROR_LOG_CHARS);
}

